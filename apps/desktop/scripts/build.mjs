import { build } from 'esbuild';
import { cp, mkdir, rm, writeFile, access } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve, relative } from 'node:path';
import { execFileSync } from 'node:child_process';
import { bundleTools } from './bundle-tools.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const repo = resolve(root, '../..');
const dist = resolve(root, 'dist');
const runtime = resolve(dist, 'runtime');
const pnpm = (args) => execFileSync('npx', ['--yes', 'pnpm@10.33.0', ...args], { cwd: repo, stdio: 'inherit' });
const base = { bundle: true, platform: 'node', target: 'node24', sourcemap: true, absWorkingDir: root,
  alias: { '@nightshift/contract': resolve(repo, 'packages/contract/src/index.ts') } };
await rm(dist, { recursive: true, force: true });
await mkdir(runtime, { recursive: true });
// A production Vite build uses the engine on the page's origin, including in desktop dev.
pnpm(['--filter', '@nightshift/web', 'build']);
pnpm(['--filter', '@nightshift/contract', 'build']);
pnpm(['--filter', '@nightshift/editor', 'build']);
await build({ ...base, entryPoints: ['src/main.ts', 'src/engine-worker.ts', 'src/preload.ts'], outdir: 'dist', format: 'cjs', outExtension: { '.js': '.cjs' }, external: ['electron'] });
// Keep the engine's original depth so its sample-recipe fallback resolves without patching engine code.
await build({ ...base, entryPoints: [resolve(repo, 'packages/engine/src/index.ts')], outfile: 'dist/runtime/packages/engine/dist/engine.mjs', format: 'esm',
  banner: { js: "import { createRequire as desktopCreateRequire } from 'node:module'; const require = desktopCreateRequire(import.meta.url);" } });
await cp(resolve(repo, 'apps/web/dist'), resolve(runtime, 'web'), { recursive: true });
for (const dir of ['recipes', 'workflows', 'comfy_nodes']) {
  try { await access(resolve(repo, dir)); }
  catch { await mkdir(resolve(runtime, dir), { recursive: true }); continue; }
  await cp(resolve(repo, dir), resolve(runtime, dir), { recursive: true });
}
await cp(resolve(repo, 'packages/engine/fixtures/recipes'), resolve(runtime, 'packages/engine/fixtures/recipes'), { recursive: true });
// Preserve the editor's package layout, dynamic font lookup, HyperFrames runtime assets and workers.
// Browser compositions are generated by editor code. There are no separate template files.
pnpm(['--filter', '@nightshift/editor', 'deploy', '--legacy', '--prod', resolve(runtime, 'packages/editor')]);
// Remove pnpm's source-checkout self-link. The deployed entry is imported by its file path.
// Keeping a self-link also makes the macOS signing walker recurse into the package again.
const editorSelf = resolve(runtime, 'packages/editor/node_modules/.pnpm/node_modules/@nightshift/editor');
await rm(editorSelf, { force: true });
const editor = await import(pathToFileURL(resolve(runtime, 'packages/editor/dist/index.js')).href);
const browserCache = resolve(root, 'artifacts/render-browser');
const chrome = await editor.ensureRenderBrowser({ cacheDir: browserCache });
await cp(browserCache, resolve(runtime, 'render-browser'), { recursive: true });
await bundleTools(runtime);
await writeFile(resolve(runtime, 'resources.json'), JSON.stringify({ chrome: relative(browserCache, chrome) }, null, 2));
console.log('Built desktop with the real engine, UI, editor and runtime resources.');
